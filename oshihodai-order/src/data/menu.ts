interface Extra {
  badges?: ItemBadge[]
  rank?: number
  options?: OptionGroupId[]
  kana?: string
}

interface Def {
  name: string
  price: number
  description: string
  emoji: string
  extra: Extra
}

function def(name: string, price: number, description: string, emoji: string, extra: Extra = {}): Def {
  return { name, price, description, emoji, extra }
}

function sub(subCategory: string, defs: Def[]): [string, Def[]] {
  return [subCategory, defs]
}

function build(category: CategoryId, groups: [string, Def[]][]): MenuItem[] {
  const items: MenuItem[] = []
  let i = 0
  for (const [subCategory, defs] of groups) {
    for (const d of defs) {
      i += 1
      items.push({
        id: `${category}-${String(i).padStart(3, '0')}`,
        name: d.name,
        kana: d.extra.kana,
        category,
        subCategory,
        price: d.price,
        description: d.description,
        emoji: d.emoji,
        gradient: GRADIENTS[category][i % GRADIENTS[category].length],
        badges: d.extra.badges,
        rank: d.extra.rank,
        options: d.extra.options,
      })
    }
  }
  return items
}

